def cites(keys, table):
    return [table[k] for k in keys if k in table]


def build():
    # итоговые теги из мастера
    wb = openpyxl.load_workbook(MASTER, data_only=True)
    ws = wb[SHEET]
    final = {}
    for r in ws.iter_rows(min_row=15, max_row=ws.max_row):
        v = r[16].value
        if v and str(v).strip() in ("ККО", "ИНФРАСТРУКТУРА", "ККО, ИНФРАСТРУКТУРА"):
            final[r[0].row] = str(v).strip()

    # данные строк из сверки
    sv = {}
    for row in openpyxl.load_workbook(SVERKA)["Сверка"].iter_rows(min_row=2, values_only=True):
        if row[0] is None:
            continue
        sv[int(row[0])] = dict(razd=row[1], pod=row[2], name=row[3] or "", note=row[4] or "",
                               q=str(row[5]), verdict=str(row[7]))

    out = []
    for rn in sorted(final):
        tag = final[rn]
        d = sv.get(rn, {})
        name, note = str(d.get("name", "")), str(d.get("note", ""))
        blob = name + " || " + note
        K  = S.hits(S.KKO, blob)
        I  = S.hits(S.INFRA, blob)
        Kw = S.hits(S.KKO_WEAK, blob)
        Iw = S.hits(S.INFRA_WEAK, blob)

        if tag == "ККО, ИНФРАСТРУКТУРА":
            typ = "общая для обоих стандартов"
            parts = ["Позиция без привязки к конкретной системе — присутствует в номенклатуре и Альбома точек продаж, и бранч-бука инфраструктуры."]
            parts += cites(K, CITE_KKO) + cites(I, CITE_INFRA)
            if not K and not I:
                low = name.lower()
                if "tikkurila" in low or "окрас" in low:
                    parts.append("Краска Tikkurila EURO 7 — базовая в обоих стандартах (ТП: RAL 7047/3020; инфраструктура: RAL 9010/9005).")
                elif "перегород" in low or "светопрозрачн" in low or "стеклянн" in low:
                    parts.append("Светопрозрачные/стеклянные перегородки и двери есть в обоих: ТП — NAYADA-Crystal (зона 6.7); инфраструктура — Pilkington 2×10 / Versal (свод «Все зоны»).")
            obosn = " ".join(parts)
        elif tag == "ККО":
            if K:
                typ = "прямая позиция бранч-бука"
                obosn = "Тег ККО — позиция прямо указана в Альбоме точек продаж. " + " • ".join(cites(K, CITE_KKO))
            elif Kw:
                typ = "косвенно (палитра / номенклатура)"
                obosn = "Тег ККО — точной модели в бранч-буке нет, отнесение по косвенным признакам. " + " • ".join(cites(Kw, CITE_KWEAK))
            else:
                typ = "по смыслу раздела"
                obosn = "Тег ККО — модель в бранч-буке не найдена, отнесение по смыслу раздела (см. лист «Сверка»)."
        else:  # ИНФРАСТРУКТУРА
            if I:
                typ = "прямая позиция бранч-бука"
                obosn = "Тег ИНФРАСТРУКТУРА — позиция прямо указана в бранч-буке инфраструктуры. " + " • ".join(cites(I, CITE_INFRA))
            elif Iw:
                typ = "косвенно (палитра / номенклатура)"
                obosn = "Тег ИНФРАСТРУКТУРА — точной модели нет, отнесение по косвенным признакам. " + " • ".join(cites(Iw, CITE_IWEAK))
            else:
                typ = "по смыслу раздела"
                obosn = "Тег ИНФРАСТРУКТУРА — модель в бранч-буке не найдена, отнесение по смыслу раздела (см. лист «Сверка»)."

        out.append(dict(row=rn, razd=d.get("razd", ""), pod=d.get("pod", ""),
                        name=name, tag=tag, typ=typ, obosn=obosn))
    return out


